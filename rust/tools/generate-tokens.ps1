$ErrorActionPreference = 'Stop'

$toolsDirectory = $PSScriptRoot
$rustDirectory = Split-Path -Parent $toolsDirectory
$repositoryRoot = Split-Path -Parent $rustDirectory

$styleFiles = @(
    'Telegram/SourceFiles/luxury/ui/luxury_styles.style',
    'Telegram/SourceFiles/luxury/ui/luxury_icons.style',
    'Telegram/SourceFiles/luxury/ui/settings/luxury_settings.style'
)

$pattern = '^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*(-?[0-9]+(?:\.[0-9]+)?)(px)?\s*;\s*$'
$tokens = [ordered]@{}

foreach ($relative in $styleFiles) {
    $path = Join-Path $repositoryRoot $relative
    if (-not (Test-Path $path)) {
        throw "Missing fork style file: $relative"
    }
    $lineNumber = 0
    foreach ($line in [System.IO.File]::ReadAllLines($path)) {
        $lineNumber++
        $match = [regex]::Match($line, $pattern)
        if (-not $match.Success) {
            continue
        }
        $name = [regex]::Replace($match.Groups[1].Value, '(?<=[a-z0-9])([A-Z])', '_$1').ToUpperInvariant()
        $number = [double]::Parse($match.Groups[2].Value, [System.Globalization.CultureInfo]::InvariantCulture)
        $value = $number.ToString('0.0#####', [System.Globalization.CultureInfo]::InvariantCulture)
        $unit = if ($match.Groups[3].Success) { 'px' } else { 'unitless' }
        if (-not $tokens.Contains($name)) {
            $tokens[$name] = [pscustomobject]@{
                Name = $name
                Value = $value
                Source = "$relative`:$lineNumber"
                Original = "$($match.Groups[2].Value)$unit"
            }
        }
    }
}

if ($tokens.Count -eq 0) {
    throw 'No scalar design tokens were found in the fork style files.'
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// Generated by rust/tools/generate-tokens.ps1. Do not edit by hand.')
$lines.Add('//! Scalar design tokens extracted from LuxuryGram''s fork-specific `.style` files.')
$lines.Add('//! Composite values (margins, point, icon, colors) are not covered yet.')
$lines.Add('')
foreach ($token in $tokens.Values) {
    $lines.Add("/// Source: $($token.Source) - $($token.Original)")
    $lines.Add("pub const $($token.Name): f32 = $($token.Value);")
}
$lines.Add('')
$lines.Add('#[cfg(test)]')
$lines.Add('mod tests {')
$lines.Add('    use super::*;')
$lines.Add('')
$lines.Add('    #[test]')
$lines.Add('    fn fork_tokens_have_expected_values() {')
$lines.Add('        assert_eq!(ICON_PICKER_ICON_SIZE, 64.0);')
$lines.Add('        assert_eq!(LUXURY_TOOLTIP_DELAY, 350.0);')
$lines.Add('    }')
$lines.Add('}')
$lines.Add('')

$targetDirectory = Join-Path $rustDirectory 'crates/design-tokens/src'
New-Item -ItemType Directory -Force -Path $targetDirectory | Out-Null
$target = Join-Path $targetDirectory 'lib.rs'
[System.IO.File]::WriteAllLines($target, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Output "Generated $($tokens.Count) tokens in $target"
